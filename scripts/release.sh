#!/bin/bash
# Build, package and publish a GitHub release of Album Artwork.
#
# Usage: bash scripts/release.sh [VERSION] [--notes FILE] [--draft] [--yes] [--dry-run]
#
#   VERSION     Defaults to CFBundleShortVersionString in Support/Info.plist.
#               If given, it must match Info.plist (bump the plist first).
#   --notes     Markdown release notes. Defaults to docs/releases/VERSION.md if it
#               exists, otherwise GitHub's generated notes since the last tag.
#   --draft     Create the GitHub release as a draft.
#   --yes       Don't ask for confirmation before tagging and publishing.
#   --dry-run   Skip the git/GitHub checks and publishing; only build, zip and checksum.
#
# Must run on an up-to-date, clean `main`. Produces dist/Album-Artwork-VERSION.zip
# (universal arm64 + x86_64, ad hoc signed) and a matching .sha256 file, tags
# vVERSION, pushes the tag and creates the GitHub release with both files attached.
set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$PROJECT_DIR"

die() { printf 'release: %s\n' "$*" >&2; exit 1; }
step() { printf '\n==> %s\n' "$*"; }

VERSION=""
NOTES_FILE=""
DRAFT=0
ASSUME_YES=0
DRY_RUN=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --notes) [[ $# -ge 2 ]] || die "--notes needs a file"; NOTES_FILE="$2"; shift 2 ;;
        --draft) DRAFT=1; shift ;;
        --yes|-y) ASSUME_YES=1; shift ;;
        --dry-run) DRY_RUN=1; shift ;;
        -h|--help) sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        -*) die "unknown option: $1" ;;
        *) [[ -z "$VERSION" ]] || die "unexpected argument: $1"; VERSION="${1#v}"; shift ;;
    esac
done

PLIST_VERSION="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' Support/Info.plist)"
VERSION="${VERSION:-$PLIST_VERSION}"
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "version must look like 1.2.3 (got '$VERSION')"
[[ "$VERSION" == "$PLIST_VERSION" ]] \
    || die "Support/Info.plist says $PLIST_VERSION, not $VERSION. Bump CFBundleShortVersionString (and CFBundleVersion) on main first."
TAG="v$VERSION"

if [[ -z "$NOTES_FILE" && -f "docs/releases/$VERSION.md" ]]; then
    NOTES_FILE="docs/releases/$VERSION.md"
fi
[[ -z "$NOTES_FILE" || -f "$NOTES_FILE" ]] || die "notes file not found: $NOTES_FILE"

if [[ "$DRY_RUN" == "0" ]]; then
    step "Checking repository state"
    command -v gh >/dev/null || die "GitHub CLI (gh) is required"
    gh auth status >/dev/null 2>&1 || die "gh is not logged in (run: gh auth login)"
    BRANCH="$(git symbolic-ref --quiet --short HEAD || true)"
    [[ "$BRANCH" == "main" ]] || die "releases must be made from main (current: ${BRANCH:-detached HEAD})"
    git diff --quiet HEAD -- || die "tracked files have uncommitted changes; commit or stash them first"
    git fetch --quiet --tags origin main
    [[ "$(git rev-parse HEAD)" == "$(git rev-parse origin/main)" ]] \
        || die "local main is not identical to origin/main; pull or push first"
    ! git rev-parse -q --verify "refs/tags/$TAG" >/dev/null || die "tag $TAG already exists"
    ! git ls-remote --exit-code --tags origin "refs/tags/$TAG" >/dev/null 2>&1 || die "tag $TAG already exists on origin"
    ! gh release view "$TAG" >/dev/null 2>&1 || die "GitHub release $TAG already exists"
fi

step "Running tests"
bash scripts/test.sh

step "Building universal app"
UNIVERSAL=1 bash scripts/build.sh
APP="build/Album Artwork.app"
lipo "$APP/Contents/MacOS/AlbumArtwork" -verify_arch arm64 x86_64 || die "binary is not universal"
BUILT_VERSION="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$APP/Contents/Info.plist")"
[[ "$BUILT_VERSION" == "$VERSION" ]] || die "built app reports $BUILT_VERSION, expected $VERSION"

step "Packaging"
DIST="dist"
ZIP_NAME="Album-Artwork-$VERSION.zip"
mkdir -p "$DIST"
rm -f "$DIST/$ZIP_NAME" "$DIST/$ZIP_NAME.sha256"
ditto -c -k --sequesterRsrc --keepParent "$APP" "$DIST/$ZIP_NAME"
(cd "$DIST" && shasum -a 256 "$ZIP_NAME" > "$ZIP_NAME.sha256" && shasum -a 256 -c "$ZIP_NAME.sha256")
SHA256="$(cut -d' ' -f1 "$DIST/$ZIP_NAME.sha256")"

# Release body: notes, then the checksum.
BODY_FILE="$(mktemp -t album-artwork-release)"
trap 'rm -f "$BODY_FILE"' EXIT
NOTES_ARGS=()
if [[ -n "$NOTES_FILE" ]]; then
    cat "$NOTES_FILE" > "$BODY_FILE"
    printf '\n' >> "$BODY_FILE"
else
    NOTES_ARGS=(--generate-notes)
fi
cat >> "$BODY_FILE" <<EOF
## Checksum

\`\`\`
$SHA256  $ZIP_NAME
\`\`\`

Verify with \`shasum -a 256 -c $ZIP_NAME.sha256\` in the folder holding both files.
EOF

printf '\nVersion:  %s (tag %s)\nArchive:  %s/%s\nSHA-256:  %s\nNotes:    %s\n' \
    "$VERSION" "$TAG" "$DIST" "$ZIP_NAME" "$SHA256" "${NOTES_FILE:-generated by GitHub}"

if [[ "$DRY_RUN" == "1" ]]; then
    printf '\nDry run: nothing tagged or published. Release body:\n\n'
    cat "$BODY_FILE"
    exit 0
fi

if [[ "$ASSUME_YES" == "0" ]]; then
    read -r -p "Tag $TAG at $(git rev-parse --short HEAD), push it, and publish the release? [y/N] " reply
    [[ "$reply" =~ ^[Yy]$ ]] || die "aborted"
fi

step "Tagging $TAG"
git tag -a "$TAG" -m "Album Artwork $VERSION"
git push origin "refs/tags/$TAG"

step "Creating GitHub release"
RELEASE_ARGS=(--title "Album Artwork $VERSION" --notes-file "$BODY_FILE" --verify-tag)
[[ "$DRAFT" == "1" ]] && RELEASE_ARGS+=(--draft)
gh release create "$TAG" "$DIST/$ZIP_NAME" "$DIST/$ZIP_NAME.sha256" \
    "${RELEASE_ARGS[@]}" ${NOTES_ARGS[@]+"${NOTES_ARGS[@]}"}

printf '\nReleased %s\n' "$(gh release view "$TAG" --json url --jq .url)"
